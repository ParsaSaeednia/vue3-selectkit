test('preview, matching Select all, slots, copy and console health', async ({
  page,
  context,
  browserName,
}) => {
  const errors: string[] = []
  page.on('pageerror', (e) => errors.push(e.message))
  if (browserName === 'chromium')
    await context.grantPermissions(['clipboard-read', 'clipboard-write'])
  await page.goto('./')
  await expect(page.getByRole('heading', { name: 'Build your select.' })).toBeVisible()
  const search = page.getByRole('combobox', { name: 'Search options...' })
  await expect(search).toBeVisible()
  await search.fill('Solid')
  await expect(page.locator('.vsk-listbox [role=option]')).toHaveCount(1)
  await page.getByRole('checkbox', { name: 'Select all', exact: true }).click()
  await expect(page.getByTestId('selected-value')).toHaveText('[1,3,4]')
  await page.getByRole('tab', { name: 'Slots', exact: true }).click()
  await page.getByLabel('Selection slot', { exact: true }).selectOption('count')
  await expect(page.locator('.vsk-selection')).toHaveText('3 selected')
  await page.getByRole('button', { name: 'Copy code' }).click()
  await expect(page.getByRole('button', { name: 'Copied!' })).toBeVisible()
  if (browserName === 'chromium') {
    const copied = await page.evaluate(() => navigator.clipboard.readText())
    expect(copied).toContain('#selection')
    expect(copied).toContain("from 'vue3-selectkit'")
  }
  expect(errors).toEqual([])
})
test('keyboard and full-list virtualization stay bounded and accessible', async ({ page }) => {
  await page.goto('./')
  await page.getByRole('switch', { name: 'Virtual scrolling', exact: true }).click()
  await page.getByRole('combobox', { name: 'Frameworks', exact: true }).click()
  const search = page.getByRole('combobox', { name: 'Search options...' })
  await expect(search).toBeVisible()
  await expect.poll(() => page.locator('.vsk-listbox [role=option]').count()).toBeGreaterThan(0)
  expect(await page.locator('.vsk-listbox [role=option]').count()).toBeLessThan(100)
  await search.press('Control+End')
  await expect(page.locator('[data-highlighted=true]')).toContainText('Framework 10000')
  const activeId = await search.getAttribute('aria-activedescendant')
  expect(await page.locator(`[id="${activeId}"]`).count()).toBe(1)
  await search.press('Enter')
  await expect(page.getByTestId('selected-value')).toContainText('10000')
  await page.getByRole('checkbox', { name: 'Select all', exact: true }).click()
  const result = JSON.parse(await page.getByTestId('selected-value').innerText())
  expect(result).toHaveLength(10000)
  expect(await page.locator('.vsk-listbox [role=option]').count()).toBeLessThan(100)
})
