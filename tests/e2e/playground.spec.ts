test('light and dark themes, unstyled mode and automated accessibility', async ({ page }) => {
  await page.goto('./')
  const initial = await new AxeBuilder({ page }).analyze()
  expect(
    initial.violations.map((v) => ({ id: v.id, nodes: v.nodes.map((n) => n.target) })),
  ).toEqual([])
  await page.getByRole('button', { name: 'Use dark theme' }).click()
  await expect(page.locator('html')).toHaveClass(/\bdark\b/)
  const dark = await new AxeBuilder({ page }).analyze()
  expect(dark.violations.map((v) => v.id)).toEqual([])
  await page.getByRole('switch', { name: 'Unstyled', exact: true }).click()
  await expect(page.locator('.vsk-root')).toHaveAttribute('data-unstyled', 'true')
  await page.getByRole('button', { name: 'Use light theme' }).click()
})
